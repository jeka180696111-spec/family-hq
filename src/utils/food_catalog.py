def _normalize(name: str) -> str:
    """Нормализация: lower, ё → е, обрезать пробелы, множ. число → ед."""
    if not name:
        return ""
    s = name.strip().lower().replace("ё", "е")
    # Убираем часто добавляемые суффиксы типа «кашка», «пюре»
    for suffix in (" пюре", " кашка", " каша", " суп"):
        if s.endswith(suffix) and len(s) > len(suffix) + 2:
            s = s[: -len(suffix)]
    return s


def guess_emoji(name: str) -> str:
    """Угадать эмодзи по названию продукта."""
    n = _normalize(name)
    if not n:
        return "🥄"
    if n in _PRODUCTS:
        return _PRODUCTS[n][0]
    # Fuzzy: ищем самое длинное вхождение известного продукта в введённой строке
    best = None
    for key in _PRODUCTS:
        if key in n or n in key:
            if best is None or len(key) > len(best):
                best = key
    if best:
        return _PRODUCTS[best][0]
    return "🥄"


def guess_category(name: str) -> str:
    """Угадать категорию продукта."""
    n = _normalize(name)
    if not n:
        return _CAT_ДРУГОЕ
    if n in _PRODUCTS:
        return _PRODUCTS[n][1]
    best = None
    for key in _PRODUCTS:
        if key in n or n in key:
            if best is None or len(key) > len(best):
                best = key
    if best:
        return _PRODUCTS[best][1]
    return _CAT_ДРУГОЕ


def to_try_now(age_months: float, already_tried: set[str]) -> list[dict]:
    """Что стоит попробовать в этом возрасте, чего ещё не пробовали.

    Возвращает список dict {name, emoji, category, min_age} — отсортирован
    по возрасту (самое раннее — сверху).
    """
    already_norm = {_normalize(t) for t in already_tried}
    out = []
    for name, min_age in _MIN_AGE.items():
        if min_age > age_months + 0.5:
            continue  # ещё рано
        if name in already_norm:
            continue
        emoji, cat = _PRODUCTS.get(name, ("🥄", _CAT_ДРУГОЕ))
        out.append({
            "name": name,
            "emoji": emoji,
            "category": cat,
            "min_age": min_age,
        })
    out.sort(key=lambda x: (x["min_age"], x["name"]))
    return out


def all_category_slugs() -> list[dict]:
    """Все категории в порядке отображения: {slug, emoji}."""
    return [{"slug": s, "emoji": e} for s, e in CATEGORIES]
